#!/usr/bin/env python3
"""How far the Rust core matches the Java mod, read off their tests, with no Java run.

The mod's game tests are the spec: each `@GameTest` method in core/src/main/java/dev/b28/enterprise/test/ pins one
behaviour. A Rust test in sim/ that covers one says so in a comment, `// parity: CaravanTests.aTownPromisesOnlyWhatItSells`
(one per line; several may share a Rust test, and `parity-partial:` marks one covered only in part). Behaviours that
won't come to the core (Minecraft's own: blocks, entities, the client) are listed in scripts/parity-skip.txt, one
`File.method` a line with a reason after `#`.

    python3 scripts/parity.py             a summary by test file
    python3 scripts/parity.py --left      every Java test not yet covered, by file
    python3 scripts/parity.py --md FILE   the whole table as Markdown (docs/parity.md)
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVA = ROOT / "core/src/main/java/dev/b28/enterprise/test"
RUST = ROOT / "sim"
SKIP = ROOT / "scripts/parity-skip.txt"


def java_tests():
    out = defaultdict(list)
    for f in sorted(JAVA.glob("*.java")):
        text = f.read_text()
        for m in re.finditer(r"@GameTest\b[^\n]*\n(?:\s*@[^\n]*\n)*\s*public static void (\w+)\(", text):
            out[f.stem].append(m.group(1))
    return out


def rust_claims():
    full, partial = defaultdict(list), defaultdict(list)
    for f in sorted(RUST.rglob("*.rs")):
        if "target" in f.parts:
            continue
        lines = f.read_text().splitlines()
        for i, line in enumerate(lines):
            m = re.search(r"//\s*parity(-partial)?:\s*(\w+)\.(\w+)", line)
            if not m:
                continue
            # The Rust test it belongs to: the next `fn` below the tag.
            test = next((re.search(r"fn (\w+)", l).group(1) for l in lines[i:i + 8] if re.search(r"fn (\w+)", l)), "?")
            where = f"{f.relative_to(ROOT)}::{test}"
            (partial if m.group(1) else full)[f"{m.group(2)}.{m.group(3)}"].append(where)
    return full, partial


def skips():
    out = {}
    if SKIP.exists():
        for line in SKIP.read_text().splitlines():
            key, _, why = line.partition("#")
            if key.strip():
                out[key.strip()] = why.strip()
    return out


def main():
    tests = java_tests()
    full, partial = rust_claims()
    skip = skips()
    for key in [k for k in skip if k.endswith(".*")]:  # a whole file: File.*
        for t in tests.get(key[:-2], []):
            skip.setdefault(f"{key[:-2]}.{t}", skip[key])
        del skip[key]
    known = {f"{f}.{t}" for f, ts in tests.items() for t in ts}
    unknown = sorted(k for k in list(full) + list(partial) + list(skip) if k not in known)
    total = len(known)
    covered = sum(1 for k in known if k in full)
    halfway = sum(1 for k in known if k in partial and k not in full)
    skipped = sum(1 for k in known if k in skip and k not in full and k not in partial)
    if "--md" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--md") + 1])
        rows = ["# Parity: the Rust core against the mod's game tests", "",
                f"Generated by `scripts/parity.py --md`. {covered} of {total} covered, {halfway} in part, "
                f"{skipped} not for the core (Minecraft's own).", "",
                "| Java test | Rust | |", "|---|---|---|"]
        for f, ts in tests.items():
            for t in ts:
                k = f"{f}.{t}"
                status, where = ("✅", full[k]) if k in full else ("🟡", partial[k]) if k in partial else \
                    ("—", [skip[k]]) if k in skip else ("", [])
                rows.append(f"| `{k}` | {'<br>'.join(w.split('::')[-1] for w in where)} | {status} |")
        out.write_text("\n".join(rows) + "\n")
        print(f"wrote {out}")
    width = max(len(f) for f in tests)
    print(f"{'test file':{width}}  covered  partial  skipped  left")
    for f, ts in tests.items():
        keys = [f"{f}.{t}" for t in ts]
        c = sum(k in full for k in keys)
        p = sum(k in partial and k not in full for k in keys)
        s = sum(k in skip and k not in full and k not in partial for k in keys)
        print(f"{f:{width}}  {c:7}  {p:7}  {s:7}  {len(keys) - c - p - s:4}")
    print(f"{'all':{width}}  {covered:7}  {halfway:7}  {skipped:7}  {total - covered - halfway - skipped:4}   of {total}")
    if unknown:
        print("\nTags naming no Java test (renamed?): " + ", ".join(unknown))
    if "--left" in sys.argv:
        for f, ts in tests.items():
            left = [t for t in ts if f"{f}.{t}" not in full and f"{f}.{t}" not in partial and f"{f}.{t}" not in skip]
            if left:
                print(f"\n{f}:")
                for t in left:
                    print(f"  {t}")


if __name__ == "__main__":
    main()
