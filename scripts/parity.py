#!/usr/bin/env python3
"""How far the Rust core matches the Java mod, read off their tests, with no Java run.

The mod's game tests are the spec: each `@GameTest` method in core/src/main/java/dev/b28/enterprise/test/ pins one
behaviour. A Rust test in sim/ that covers one says so in a comment, `// parity: CaravanTests.aTownPromisesOnlyWhatItSells`
(one per line; several may share a Rust test, and `parity-partial:` marks one covered only in part). Behaviours that
won't come to the core (Minecraft's own: blocks, entities, the client) are listed in scripts/parity-skip.txt, one
`File.method` a line with a reason after `#`.

    python3 scripts/parity.py             a summary by test file
    python3 scripts/parity.py --left      every Java test not yet covered, by file
    python3 scripts/parity.py --md FILE   the whole table as Markdown (docs/parity.md)
    python3 scripts/parity.py --binding   every game test sorted for the Minecraft binding (docs/binding-plan.md
                                          section 2) into docs/binding-tests.md: world fixture / rule API / Minecraft's own
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVA = ROOT / "core/src/main/java/dev/b28/enterprise/test"
RUST = ROOT / "sim"
SKIP = ROOT / "scripts/parity-skip.txt"
TARGET = 190  # covered, of the non-skipped: docs/core-plan.md's closing number


def java_tests():
    out = defaultdict(list)
    for f in sorted(JAVA.glob("*.java")):
        text = f.read_text()
        for m in re.finditer(r"@GameTest\b[^\n]*\n(?:\s*@[^\n]*\n)*\s*public static void (\w+)\(", text):
            out[f.stem].append(m.group(1))
    return out


# What makes a test a world fixture: it builds or reads blocks, spawns entities or players, or waits on the game
# clock. A test with none of these only calls Java rules on data (a "rule API" test). Private helpers in the same
# file count: a test that calls a helper which builds a town is a fixture too.
FIXTURE = re.compile(
    r"\bsetBlock\(|\bspawn\w*\(|\bgetBlockEntity\(|\bgetBlockState\(|\bgetEntity\(|\bgetEntities\w*\(|"
    r"\bmakeMock\w*\(|\bstartSequence\(|\bsucceedWhen\w*\(|\brunAfter\w*\(|\bBlocks\.[A-Z]|\bEntityType\.[A-Z]|"
    r"\bfillBlocks?\(|\bsetNight\(|\bsetDayTime\(")


def method_bodies(text):
    """Every method in a Java file (private helpers too) as name -> body, found by brace matching."""
    out = {}
    for m in re.finditer(r"^    (?:public |private |protected )?(?:static )(?:[\w<>\[\], .?]+ )(\w+)\([^;{]*\)[^;{]*\{",
                         text, re.M):
        depth, i = 1, m.end()
        while i < len(text) and depth:
            c = text[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            elif c == '"':  # skip a string, which may hold a brace
                i += 1
                while text[i] != '"':
                    i += 2 if text[i] == "\\" else 1
            i += 1
        out[m.group(1)] = text[m.end():i]
    return out


def fixtures():
    """The set of `File.method` game tests that are world fixtures."""
    found = set()
    for f in sorted(JAVA.glob("*.java")):
        bodies = method_bodies(f.read_text())
        memo = {}

        def is_fixture(name, seen=()):
            if name not in memo:
                body = bodies[name]
                memo[name] = bool(FIXTURE.search(body)) or any(
                    other != name and other not in seen and re.search(r"\b" + other + r"\(", body)
                    and is_fixture(other, seen + (name,)) for other in bodies)
            return memo[name]

        for t in java_tests().get(f.stem, []):
            if t in bodies and is_fixture(t):
                found.add(f"{f.stem}.{t}")
    return found


def binding_report(tests, full, partial, skip):
    """Sort every game test: Minecraft's own (parity-skip.txt), else world fixture, else rule API. Writes
    docs/binding-tests.md and returns the rule-API tests with no full Rust twin."""
    fixture = fixtures()
    kinds = defaultdict(list)
    for f, ts in tests.items():
        for t in ts:
            k = f"{f}.{t}"
            kind = "own" if k in skip and k not in full and k not in partial else "fixture" if k in fixture else "rule"
            kinds[kind].append(k)
    no_twin = [k for k in kinds["rule"] if k not in full]
    total = sum(len(v) for v in kinds.values())
    rows = ["# Game tests sorted for the binding", "",
            "Generated by `python3 scripts/parity.py --binding` (docs/binding-plan.md section 2); do not edit by hand. "
            "Each `@GameTest` is one of:", "",
            f"- **World fixture** ({len(kinds['fixture'])}): builds or reads blocks, spawns villagers or players, or waits on "
            "the game clock, then asserts an outcome in the world. These become the binding's acceptance tests, "
            "rewritten where they call a Java rule so they drive the core through the binding; green in core mode is a "
            "concern's gate.",
            f"- **Rule API** ({len(kinds['rule'])}): calls Java rule classes on plain data, no world to speak of. Retired "
            "with the class they pin; the Rust twin (a `parity:` tag) stands in. One with no full twin has to move to the "
            "core first.",
            f"- **Minecraft's own** ({len(kinds['own'])}): listed in `scripts/parity-skip.txt`; blocks, entities, the client. "
            "Kept as the binding's view tests.", "",
            f"{total} tests. A test is a fixture if its body (or a private helper it calls in the same file) uses "
            "`setBlock`, `spawn`, block or entity reads, mock players, sequences or `succeedWhen`; a skip-listed test is "
            "Minecraft's own whatever its body does.", "",
            "## Rule-API tests with no full Rust twin", ""]
    if no_twin:
        rows += ["These go to the core first.", "", "| Java test | Rust |", "|---|---|"]
        for k in no_twin:
            rows.append(f"| `{k}` | {'in part: ' + ', '.join(w.split('::')[-1] for w in partial[k]) if k in partial else 'none'} |")
    else:
        rows.append("None: every rule-API test has a full Rust twin.")
    rows += ["", "## By test file", "", "| Test file | World fixture | Rule API | Minecraft's own |", "|---|---|---|---|"]
    for f in tests:
        n = {kd: sum(1 for k in kinds[kd] if k.startswith(f + ".")) for kd in kinds}
        rows.append(f"| {f} | {n.get('fixture', 0)} | {n.get('rule', 0)} | {n.get('own', 0)} |")
    rows += ["", "## Every test", "", "| Java test | Kind | Rust twin |", "|---|---|---|"]
    label = {"fixture": "world fixture", "rule": "rule API", "own": "Minecraft's own"}
    for f, ts in tests.items():
        for t in ts:
            k = f"{f}.{t}"
            kind = next(kd for kd in kinds if k in kinds[kd])
            twin = "<br>".join(w.split("::")[-1] for w in full[k]) if k in full else \
                ("part: " + "<br>".join(w.split("::")[-1] for w in partial[k])) if k in partial else \
                "—" if kind == "own" else "none"
            rows.append(f"| `{k}` | {label[kind]} | {twin} |")
    out = ROOT / "docs/binding-tests.md"
    out.write_text("\n".join(rows) + "\n")
    print(f"wrote {out}")
    print(f"\nworld fixture {len(kinds['fixture'])}, rule API {len(kinds['rule'])}, Minecraft's own {len(kinds['own'])}"
          f" (of {total})")
    if no_twin:
        print("\nRule-API tests with no full Rust twin (these go to the core first):")
        for k in no_twin:
            print(f"  {k}" + (" (in part)" if k in partial else ""))
    else:
        print("every rule-API test has a full Rust twin")
    return no_twin


WHY = defaultdict(list)


def rust_claims():
    """Full and partial claims by Java test; `WHY` keeps each partial's reason (the tag line's parenthesis, which may
    run on over following `//` lines, nested parentheses and all), "" where it gives none."""
    full, partial = defaultdict(list), defaultdict(list)
    for f in sorted(RUST.rglob("*.rs")):
        if "target" in f.parts:
            continue
        lines = f.read_text().splitlines()
        for i, line in enumerate(lines):
            m = re.search(r"//\s*parity(-partial)?:\s*(\w+)\.(\w+)", line)
            if not m:
                continue
            # The Rust test it belongs to: the next `fn` below the tag.
            test = next((re.search(r"fn (\w+)", l).group(1) for l in lines[i:i + 8] if re.search(r"fn (\w+)", l)), "?")
            where = f"{f.relative_to(ROOT)}::{test}"
            key = f"{m.group(2)}.{m.group(3)}"
            (partial if m.group(1) else full)[key].append(where)
            if m.group(1):
                rest, j = line[m.end():].strip(), i
                depth = lambda s: s.count("(") - s.count(")")
                while rest.startswith("(") and depth(rest) > 0 and j + 1 < len(lines) and lines[j + 1].strip().startswith("//"):
                    j += 1
                    rest += " " + lines[j].strip().lstrip("/").strip()
                why = rest[1:rest.rindex(")")] if rest.startswith("(") and ")" in rest else ""
                WHY[key].append((where, why))
    return full, partial


def skips():
    out = {}
    if SKIP.exists():
        for line in SKIP.read_text().splitlines():
            key, _, why = line.partition("#")
            if key.strip():
                out[key.strip()] = why.strip()
    return out


def main():
    tests = java_tests()
    full, partial = rust_claims()
    skip = skips()
    for key in [k for k in skip if k.endswith(".*")]:  # a whole file: File.*
        for t in tests.get(key[:-2], []):
            skip.setdefault(f"{key[:-2]}.{t}", skip[key])
        del skip[key]
    known = {f"{f}.{t}" for f, ts in tests.items() for t in ts}
    unknown = sorted(k for k in list(full) + list(partial) + list(skip) if k not in known)
    if "--binding" in sys.argv:
        binding_report(tests, full, partial, skip)
        return
    total = len(known)
    covered = sum(1 for k in known if k in full)
    halfway = sum(1 for k in known if k in partial and k not in full)
    skipped = sum(1 for k in known if k in skip and k not in full and k not in partial)
    left = total - covered - halfway - skipped
    if "--md" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--md") + 1])
        rows = ["# Parity: the Rust core against the mod's game tests", "",
                f"Generated by `scripts/parity.py --md`. {covered} of {total} covered, {halfway} in part, "
                f"{skipped} not for the core (Minecraft's own).", "",
                f"The plan's target is {TARGET} covered of the {total - skipped} the core is to match: {covered} are"
                + (f", {TARGET - covered} short, from the {halfway} in part below." if covered < TARGET else ".")
                + (f" {left} left untagged" if left else " Nothing is left untagged") + (f", and {len(unknown)} tags name no Java test: {', '.join(unknown)}."
                                              if unknown else "; no tag names a missing Java test."), "",
                "## Covered in part", "", "What each `parity-partial:` leaves out, from the test's own comment "
                "(a Java test covered in full elsewhere isn't listed).", "",
                "| Java test | Rust test | What is missing |", "|---|---|---|"]
        for k in sorted(k for k in partial if k in known and k not in full):
            for where, why in WHY[k]:
                rows.append(f"| `{k}` | `{where.split('::')[-1]}` | {why or '(no reason given)'} |")
        rows += ["", "## Every Java test", "", "| Java test | Rust | |", "|---|---|---|"]
        for f, ts in tests.items():
            for t in ts:
                k = f"{f}.{t}"
                status, where = ("✅", full[k]) if k in full else ("🟡", partial[k]) if k in partial else \
                    ("—", [skip[k]]) if k in skip else ("", [])
                rows.append(f"| `{k}` | {'<br>'.join(w.split('::')[-1] for w in where)} | {status} |")
        out.write_text("\n".join(rows) + "\n")
        print(f"wrote {out}")
    width = max(len(f) for f in tests)
    print(f"{'test file':{width}}  covered  partial  skipped  left")
    for f, ts in tests.items():
        keys = [f"{f}.{t}" for t in ts]
        c = sum(k in full for k in keys)
        p = sum(k in partial and k not in full for k in keys)
        s = sum(k in skip and k not in full and k not in partial for k in keys)
        print(f"{f:{width}}  {c:7}  {p:7}  {s:7}  {len(keys) - c - p - s:4}")
    print(f"{'all':{width}}  {covered:7}  {halfway:7}  {skipped:7}  {total - covered - halfway - skipped:4}   of {total}")
    bare = sorted(f"{k} ({w})" for k, ws in WHY.items() for w, why in ws if not why)
    unsaid = sorted(k for k, why in skip.items() if not why)
    if bare:
        print("\nPartial tags with no reason in a parenthesis: " + ", ".join(bare))
    if unsaid:
        print("\nSkips with no reason after #: " + ", ".join(unsaid))
    if unknown:
        print("\nTags naming no Java test (renamed?): " + ", ".join(unknown))
    if "--left" in sys.argv:
        for f, ts in tests.items():
            left = [t for t in ts if f"{f}.{t}" not in full and f"{f}.{t}" not in partial and f"{f}.{t}" not in skip]
            if left:
                print(f"\n{f}:")
                for t in left:
                    print(f"  {t}")


if __name__ == "__main__":
    main()
