//! The Java 21 the registry makes, in `dev.b28.enterprise.wire`: one file a type, and the runtime they share.
//!
//! | Rust | Java |
//! |---|---|
//! | a struct | a `record`, its fields in order (camelCase), each list copied and each reference checked non-null |
//! | an enum whose every variant is bare | an `enum` of the same names |
//! | any other enum | a `sealed interface`, a nested `record` a variant (a bare variant a record of nothing) |
//! | a newtype struct or variant | a record of one `value` |
//! | `bool`, `i8`, `i16`, `i32`, `i64`, `f32`, `f64` | `boolean`, `byte`, `short`, `int`, `long`, `float`, `double` |
//! | `u8`, `u16` | `int` (0 to 255, 0 to 65,535) |
//! | `u32` | `long` (0 to 4,294,967,295) |
//! | `u64`, `usize` (the ids) | `long`, its 64 bits unsigned (`Long.toUnsignedString`, `Long.compareUnsigned`) |
//! | `String` | `String` |
//! | `Vec<u8>` | `Bytes` (immutable, equal by content) |
//! | `Vec<T>`, `Option<T>` | `List<T>` (immutable), `Optional<T>` |
//!
//! Every type has `encode(PostcardOut)`, `decode(PostcardIn)`, `toBytes()` and `fromBytes(byte[])` (which refuses
//! bytes left over). A number out of its range, an unknown variant or bytes that end early throw `WireException`.

use std::collections::{BTreeMap, BTreeSet};

use serde_reflection::{ContainerFormat, Format, Named, VariantFormat};

use crate::registry::Registry;
use crate::sources::{Docs, TypeDoc};

/// The package everything is generated into.
pub const PACKAGE: &str = "dev.b28.enterprise.wire";

/// The runtime, written beside the generated types: hand-written, and pinned by the codec's tests (`tests/java.rs`).
const RUNTIME: [(&str, &str); 4] = [
    ("PostcardIn.java", include_str!("runtime/PostcardIn.java")),
    ("PostcardOut.java", include_str!("runtime/PostcardOut.java")),
    ("Bytes.java", include_str!("runtime/Bytes.java")),
    ("WireException.java", include_str!("runtime/WireException.java")),
];

const GENERATED: &str = "// Generated by sim/wire-gen from sim/core/src/wire (`just wire-gen`): don't edit.";

/// Every Java file, by file name: a file a type in the registry, the runtime, and `Wire`.
pub fn emit(registry: &Registry, docs: &Docs, schema: u64, abi: u32) -> Result<BTreeMap<String, String>, String> {
    let mut files = BTreeMap::new();
    let empty = TypeDoc::default();
    for (name, container) in registry {
        let doc = docs.get(name).unwrap_or(&empty);
        let gen = Gen { registry, name };
        let body = match container {
            ContainerFormat::UnitStruct => gen.record(&doc.doc, &[], &doc.members, None, Kind::Plain),
            ContainerFormat::NewTypeStruct(f) => {
                let fields = [Named { name: "value".to_string(), value: (**f).clone() }];
                gen.record(&doc.doc, &fields, &doc.members, None, Kind::Plain)
            }
            ContainerFormat::Struct(fields) => gen.record(&doc.doc, fields, &doc.members, None, Kind::Plain),
            ContainerFormat::Enum(variants) if variants.values().all(|v| matches!(v.value, VariantFormat::Unit)) => {
                gen.java_enum(doc, variants)
            }
            ContainerFormat::Enum(variants) => gen.sealed(doc, variants)?,
            ContainerFormat::TupleStruct(_) => return Err(format!("{name}: a tuple struct")),
        };
        files.insert(format!("{name}.java"), file(&body));
    }
    for (file_name, text) in RUNTIME {
        files.insert(file_name.to_string(), text.to_string());
    }
    files.insert("Wire.java".to_string(), file(&wire_class(registry, schema, abi)));
    Ok(files)
}

/// A file: the header, the package, the imports its body uses, the body.
fn file(body: &str) -> String {
    let mut imports = Vec::new();
    for (class, used) in [
        ("java.util.List", body.contains("List<")),
        ("java.util.Objects", body.contains("Objects.")),
        ("java.util.Optional", body.contains("Optional<")),
    ] {
        if used {
            imports.push(format!("import {class};\n"));
        }
    }
    let imports = if imports.is_empty() { String::new() } else { format!("{}\n", imports.concat()) };
    format!("{GENERATED}\npackage {PACKAGE};\n\n{imports}{body}")
}

fn wire_class(registry: &Registry, schema: u64, abi: u32) -> String {
    let has_request = matches!(registry.get("Request"), Some(ContainerFormat::Struct(f))
        if f.iter().map(|f| f.name.as_str()).eq(["abi", "schema", "command"]));
    let request = if has_request {
        "\n    /** A request for {@code command}, built against this {@link #ABI} and {@link #SCHEMA}. */\n    \
         public static Request request(Command command) {\n        return new Request(ABI, SCHEMA, command);\n    }\n"
    } else {
        ""
    };
    format!(
        "/**\n * What this generated code was built against: a request carries both, and the core refuses one built \
         against\n * another (its {{@code Refusal.Abi}} and {{@code Refusal.Schema}}).\n */\npublic final class Wire \
         {{\n    private Wire() {{}}\n\n    /** The ABI: the WebAssembly module's four exports. */\n    \
         public static final long ABI = {abi}L;\n\n    /** The schema: the FNV-1a 64 of sim/wire/registry.yaml. */\n    \
         public static final long SCHEMA = 0x{schema:016x}L;\n{request}}}\n"
    )
}

/// The Java name of a Rust field: camelCase, a Java keyword or a name records can't take given a trailing `_`.
pub fn field_name(rust: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in rust.chars() {
        if c == '_' {
            upper = !out.is_empty();
        } else if upper {
            out.push(c.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    if JAVA_RESERVED.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

/// Java's keywords and literals (`yield` among them: a method of that name can't be called plainly), and what a
/// record's component can't be named (`Object`'s methods, and the codec's). `record`, `sealed` and the other
/// contextual keywords name a component well enough.
const JAVA_RESERVED: &[&str] = &[
    "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue",
    "default", "do", "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if",
    "implements", "import", "instanceof", "int", "interface", "long", "native", "new", "package", "private",
    "protected", "public", "return", "short", "static", "strictfp", "super", "switch", "synchronized", "this",
    "throw", "throws", "transient", "try", "void", "volatile", "while", "true", "false", "null", "yield", "clone", "finalize", "getClass", "hashCode", "notify", "notifyAll",
    "toString", "wait", "toBytes",
];

/// What a record is: a plain one (a struct), or a variant of a sealed interface at its index.
#[derive(Clone, Copy)]
enum Kind<'a> {
    Plain,
    Variant { of: &'a str, index: u32 },
}

struct Gen<'a> {
    registry: &'a Registry,
    /// The type the file is for.
    name: &'a str,
}

impl Gen<'_> {
    /// A Java type for a format: boxed when it's a type argument; a wire type a nested variant shadows, qualified.
    fn ty(&self, f: &Format, boxed: bool, shadowed: &BTreeSet<String>) -> String {
        let prim = |p: &str, b: &str| if boxed { b.to_string() } else { p.to_string() };
        match f {
            Format::Bool => prim("boolean", "Boolean"),
            Format::I8 => prim("byte", "Byte"),
            Format::I16 => prim("short", "Short"),
            Format::I32 | Format::U8 | Format::U16 => prim("int", "Integer"),
            Format::I64 | Format::U32 | Format::U64 => prim("long", "Long"),
            Format::F32 => prim("float", "Float"),
            Format::F64 => prim("double", "Double"),
            Format::Str => "String".to_string(),
            Format::Bytes => "Bytes".to_string(),
            Format::Seq(inner) if **inner == Format::U8 => "Bytes".to_string(),
            Format::Seq(inner) => format!("List<{}>", self.ty(inner, true, shadowed)),
            Format::Option(inner) => format!("Optional<{}>", self.ty(inner, true, shadowed)),
            Format::TypeName(n) if shadowed.contains(n) => format!("{PACKAGE}.{n}"),
            Format::TypeName(n) => n.clone(),
            other => unreachable!("refused by registry::check: {other:?}"),
        }
    }

    fn is_reference(f: &Format) -> bool {
        !matches!(f, Format::Bool | Format::I8 | Format::I16 | Format::I32 | Format::I64 | Format::U8 | Format::U16
            | Format::U32 | Format::U64 | Format::F32 | Format::F64)
    }

    /// A `Function<PostcardIn, T>` decoding `f`: a method reference where one does, else a lambda.
    fn decoder(&self, f: &Format, depth: usize, shadowed: &BTreeSet<String>) -> String {
        match f {
            Format::TypeName(_) => format!("{}::decode", self.ty(f, false, shadowed)),
            Format::Seq(inner) if **inner != Format::U8 => self.lambda(f, depth, shadowed),
            Format::Option(_) => self.lambda(f, depth, shadowed),
            _ => {
                let call = self.decode(f, "in", depth, shadowed);
                format!("PostcardIn::{}", &call["in.".len()..call.len() - 2])
            }
        }
    }

    fn lambda(&self, f: &Format, depth: usize, shadowed: &BTreeSet<String>) -> String {
        let p = format!("i{}", depth + 1);
        format!("{p} -> {}", self.decode(f, &p, depth + 1, shadowed))
    }

    /// An expression decoding `f` from the `PostcardIn` named `input`; `depth` names the lambdas' parameters apart.
    fn decode(&self, f: &Format, input: &str, depth: usize, shadowed: &BTreeSet<String>) -> String {
        match f {
            Format::Bool => format!("{input}.bool()"),
            Format::I8 => format!("{input}.i8()"),
            Format::I16 => format!("{input}.i16()"),
            Format::I32 => format!("{input}.i32()"),
            Format::I64 => format!("{input}.i64()"),
            Format::U8 => format!("{input}.u8()"),
            Format::U16 => format!("{input}.u16()"),
            Format::U32 => format!("{input}.u32()"),
            Format::U64 => format!("{input}.u64()"),
            Format::F32 => format!("{input}.f32()"),
            Format::F64 => format!("{input}.f64()"),
            Format::Str => format!("{input}.string()"),
            Format::Bytes => format!("{input}.bytes()"),
            Format::Seq(inner) if **inner == Format::U8 => format!("{input}.bytes()"),
            Format::Seq(inner) => format!(
                "{input}.list({}, {})",
                self.min_bytes(inner, &mut BTreeSet::new()).min(i32::MAX as u64),
                self.decoder(inner, depth, shadowed)
            ),
            Format::Option(inner) => format!("{input}.option({})", self.decoder(inner, depth, shadowed)),
            Format::TypeName(_) => format!("{}.decode({input})", self.ty(f, false, shadowed)),
            other => unreachable!("refused by registry::check: {other:?}"),
        }
    }

    /// An expression (a call) encoding `value`, of `f`, to the `PostcardOut` named `output`.
    fn encode(&self, f: &Format, output: &str, value: &str, depth: usize) -> String {
        match f {
            Format::Bool => format!("{output}.bool({value})"),
            Format::I8 => format!("{output}.i8({value})"),
            Format::I16 => format!("{output}.i16({value})"),
            Format::I32 => format!("{output}.i32({value})"),
            Format::I64 => format!("{output}.i64({value})"),
            Format::U8 => format!("{output}.u8({value})"),
            Format::U16 => format!("{output}.u16({value})"),
            Format::U32 => format!("{output}.u32({value})"),
            Format::U64 => format!("{output}.u64({value})"),
            Format::F32 => format!("{output}.f32({value})"),
            Format::F64 => format!("{output}.f64({value})"),
            Format::Str => format!("{output}.string({value})"),
            Format::Bytes => format!("{output}.bytes({value})"),
            Format::Seq(inner) if **inner == Format::U8 => format!("{output}.bytes({value})"),
            Format::Seq(inner) => format!("{output}.list({value}, {})", self.encoder(inner, depth)),
            Format::Option(inner) => format!("{output}.option({value}, {})", self.encoder(inner, depth)),
            Format::TypeName(_) => format!("{value}.encode({output})"),
            other => unreachable!("refused by registry::check: {other:?}"),
        }
    }

    /// A `BiConsumer<PostcardOut, T>` encoding `f`: a method reference for a number or a string, else a lambda.
    fn encoder(&self, f: &Format, depth: usize) -> String {
        let (o, e) = (format!("o{}", depth + 1), format!("e{}", depth + 1));
        match f {
            Format::TypeName(_) | Format::Option(_) => format!("({o}, {e}) -> {}", self.encode(f, &o, &e, depth + 1)),
            Format::Seq(inner) if **inner != Format::U8 => {
                format!("({o}, {e}) -> {}", self.encode(f, &o, &e, depth + 1))
            }
            _ => {
                let call = self.encode(f, "out", "x", depth);
                format!("PostcardOut::{}", &call["out.".len()..call.len() - "(x)".len()])
            }
        }
    }

    /// The fewest bytes a value of `f` takes (a lower bound: a type met again inside itself counts nothing), so a
    /// list's length can be checked against the bytes left before anything is made for it.
    fn min_bytes(&self, f: &Format, visiting: &mut BTreeSet<String>) -> u64 {
        match f {
            Format::Unit => 0,
            Format::F32 => 4,
            Format::F64 => 8,
            Format::TypeName(n) => {
                if !visiting.insert(n.clone()) {
                    return 0;
                }
                let size = match self.registry.get(n) {
                    Some(ContainerFormat::UnitStruct) | None => 0,
                    Some(ContainerFormat::NewTypeStruct(f)) => self.min_bytes(f, visiting),
                    Some(ContainerFormat::TupleStruct(fs)) => {
                        fs.iter().fold(0u64, |s, f| s.saturating_add(self.min_bytes(f, visiting)))
                    }
                    Some(ContainerFormat::Struct(fs)) => {
                        fs.iter().fold(0u64, |s, f| s.saturating_add(self.min_bytes(&f.value, visiting)))
                    }
                    Some(ContainerFormat::Enum(_)) => 1,
                };
                visiting.remove(n);
                size
            }
            // Every other value takes a byte at least: a number, a length, a tag.
            _ => 1,
        }
    }

    /// A record: its doc (with each field's), components, the checks its constructor makes, and its codec. A variant's
    /// record is nested in its interface (indented, and writes its index first).
    fn record(&self, doc: &[String], fields: &[Named<Format>], member_docs: &BTreeMap<String, Vec<String>>,
        name: Option<&str>, kind: Kind) -> String {
        let name = name.unwrap_or(self.name);
        let shadowed = self.shadowed();
        let pad = if matches!(kind, Kind::Variant { .. }) { "    " } else { "" };
        let mut out = String::new();
        let mut javadoc_lines: Vec<String> = doc.to_vec();
        let documented: Vec<_> = fields.iter().filter_map(|f| {
            member_docs.get(&f.name).filter(|d| !d.is_empty()).map(|d| (field_name(&f.name), doc_text(&d.join(" "))))
        }).collect();
        if !documented.is_empty() {
            if !javadoc_lines.is_empty() {
                javadoc_lines.push(String::new());
            }
            for (n, d) in documented {
                javadoc_lines.push(format!("@param {n} {d}"));
            }
        }
        out.push_str(&javadoc(&javadoc_lines, pad));
        let components: Vec<String> = fields.iter()
            .map(|f| format!("{} {}", self.ty(&f.value, false, &shadowed), field_name(&f.name))).collect();
        let (visibility, implements) = match kind {
            Kind::Plain => ("public ", String::new()),
            Kind::Variant { of, .. } => ("", format!(" implements {of}")),
        };
        out.push_str(&format!("{pad}{visibility}record {name}({}){implements} {{\n", components.join(", ")));
        // The constructor: references non-null, lists copied (immutable, no nulls).
        let mut checks = Vec::new();
        for f in fields.iter().filter(|f| Self::is_reference(&f.value)) {
            let n = field_name(&f.name);
            checks.push(format!("{pad}        Objects.requireNonNull({n}, \"{n}\");\n"));
            if matches!(&f.value, Format::Seq(inner) if **inner != Format::U8) {
                checks.push(format!("{pad}        {n} = List.copyOf({n});\n"));
            }
        }
        if !checks.is_empty() {
            out.push_str(&format!("{pad}    public {name} {{\n{}{pad}    }}\n\n", checks.concat()));
        }
        // encode
        let mut writes = Vec::new();
        if let Kind::Variant { index, .. } = kind {
            writes.push(format!("out.variant({index})"));
        }
        for f in fields {
            writes.push(self.encode(&f.value, "out", &format!("this.{}", field_name(&f.name)), 0));
        }
        let over = if matches!(kind, Kind::Variant { .. }) { format!("{pad}    @Override\n") } else { String::new() };
        out.push_str(&format!("{over}{pad}    public void encode(PostcardOut out) {{\n"));
        for w in writes {
            out.push_str(&format!("{pad}        {w};\n"));
        }
        out.push_str(&format!("{pad}    }}\n"));
        if let Kind::Plain = kind {
            out.push_str(&format!(
                "\n    public static {name} decode(PostcardIn in) {{\n        return {};\n    }}\n",
                self.construct(name, fields, &shadowed)
            ));
            out.push_str(&format!(
                "\n    public byte[] toBytes() {{\n        return PostcardOut.of(this::encode);\n    }}\n\n    \
                 /** All of {{@code bytes}} read as one {name}: bytes left over are refused. */\n    \
                 public static {name} fromBytes(byte[] bytes) {{\n        return PostcardIn.read(bytes, {name}::decode);\n    }}\n"
            ));
        }
        out.push_str(&format!("{pad}}}\n"));
        out
    }

    /// `new Name(decoded, ...)`: Java evaluates arguments left to right, the order postcard wrote them.
    fn construct(&self, name: &str, fields: &[Named<Format>], shadowed: &BTreeSet<String>) -> String {
        let args: Vec<String> = fields.iter().map(|f| self.decode(&f.value, "in", 0, shadowed)).collect();
        format!("new {name}({})", args.join(", "))
    }

    /// The wire types a nested variant of this file's type would shadow: those named as one of its variants.
    fn shadowed(&self) -> BTreeSet<String> {
        match self.registry.get(self.name) {
            Some(ContainerFormat::Enum(vs)) => {
                vs.values().map(|v| v.name.clone()).filter(|n| self.registry.contains_key(n)).collect()
            }
            _ => BTreeSet::new(),
        }
    }

    /// An enum of bare variants: a Java enum of the same names, its index written as a variant's.
    fn java_enum(&self, doc: &TypeDoc, variants: &BTreeMap<u32, Named<VariantFormat>>) -> String {
        let name = self.name;
        let mut out = javadoc(&doc.doc, "");
        out.push_str(&format!("public enum {name} {{\n"));
        let n = variants.len();
        for (i, v) in variants.values().enumerate() {
            out.push_str(&javadoc(doc.members.get(&v.name).map(Vec::as_slice).unwrap_or(&[]), "    "));
            out.push_str(&format!("    {}{}\n", v.name, if i + 1 == n { ";" } else { "," }));
        }
        let to_index: Vec<String> = variants.iter().map(|(i, v)| format!("            case {} -> {i};\n", v.name)).collect();
        let from_index: Vec<String> = variants.iter().map(|(i, v)| format!("            case {i} -> {};\n", v.name)).collect();
        out.push_str(&format!(
            "\n    public void encode(PostcardOut out) {{\n        out.variant(switch (this) {{\n{}        }});\n    }}\n\n    \
             public static {name} decode(PostcardIn in) {{\n        int at = in.variant();\n        return switch (at) {{\n{}            \
             default -> throw in.unknownVariant(\"{name}\", at);\n        }};\n    }}\n\n    \
             public byte[] toBytes() {{\n        return PostcardOut.of(this::encode);\n    }}\n\n    \
             /** All of {{@code bytes}} read as one {name}: bytes left over are refused. */\n    \
             public static {name} fromBytes(byte[] bytes) {{\n        return PostcardIn.read(bytes, {name}::decode);\n    }}\n}}\n",
            to_index.concat(),
            from_index.concat()
        ));
        out
    }

    /// Any other enum: a sealed interface, a record a variant, and the decoder choosing by index.
    fn sealed(&self, doc: &TypeDoc, variants: &BTreeMap<u32, Named<VariantFormat>>) -> Result<String, String> {
        let name = self.name;
        let shadowed = self.shadowed();
        let mut out = javadoc(&doc.doc, "");
        let permits: Vec<String> = variants.values().map(|v| format!("{name}.{}", v.name)).collect();
        let header = format!("public sealed interface {name} permits {} {{\n", permits.join(", "));
        if header.len() <= 121 {
            out.push_str(&header);
        } else {
            out.push_str(&format!("public sealed interface {name}\n        permits {} {{\n",
                permits.join(",\n                ")));
        }
        out.push_str("    void encode(PostcardOut out);\n\n");
        out.push_str(&format!("    static {name} decode(PostcardIn in) {{\n        int at = in.variant();\n        return switch (at) {{\n"));
        for (i, v) in variants {
            let fields = variant_fields(&v.value)?;
            out.push_str(&format!("            case {i} -> {};\n", self.construct(&v.name, &fields, &shadowed)));
        }
        out.push_str(&format!(
            "            default -> throw in.unknownVariant(\"{name}\", at);\n        }};\n    }}\n\n    \
             default byte[] toBytes() {{\n        return PostcardOut.of(this::encode);\n    }}\n\n    \
             /** All of {{@code bytes}} read as one {name}: bytes left over are refused. */\n    \
             static {name} fromBytes(byte[] bytes) {{\n        return PostcardIn.read(bytes, {name}::decode);\n    }}\n"
        ));
        for (i, v) in variants {
            let fields = variant_fields(&v.value)?;
            let vdoc = doc.members.get(&v.name).cloned().unwrap_or_default();
            out.push('\n');
            out.push_str(&self.record(&vdoc, &fields, &BTreeMap::new(), Some(&v.name), Kind::Variant { of: name, index: *i }));
        }
        out.push_str("}\n");
        Ok(out)
    }
}

/// A variant's fields as a record's: a newtype's one `value`.
fn variant_fields(v: &VariantFormat) -> Result<Vec<Named<Format>>, String> {
    Ok(match v {
        VariantFormat::Unit => Vec::new(),
        VariantFormat::NewType(f) => vec![Named { name: "value".to_string(), value: (**f).clone() }],
        VariantFormat::Struct(fields) => fields.clone(),
        other => return Err(format!("a variant of {other:?}, refused by registry::check")),
    })
}

/// A Javadoc comment of `lines` (Rust's doc markdown made Javadoc: `code` as {@code code}), or nothing.
fn javadoc(lines: &[String], pad: &str) -> String {
    if lines.iter().all(|l| l.trim().is_empty()) {
        return String::new();
    }
    let mut out = format!("{pad}/**\n");
    let mut paragraph_break = false;
    for line in lines {
        let text = line.trim();
        if text.is_empty() {
            paragraph_break = true;
            continue;
        }
        if paragraph_break {
            out.push_str(&format!("{pad} *\n"));
            paragraph_break = false;
        }
        let text = if text.starts_with("@param ") { text.to_string() } else { doc_text(text) };
        out.push_str(&format!("{pad} * {text}\n"));
    }
    out.push_str(&format!("{pad} */\n"));
    out
}

/// One line of Rust doc as Javadoc: links and `code` as {@code}, HTML's specials escaped elsewhere.
fn doc_text(rust: &str) -> String {
    let mut out = String::new();
    let mut rest = rust.replace("[`", "`").replace("`]", "`");
    // Intra-doc link targets, `[x](y)` and `[x]: y`, have no meaning in Java: keep the words.
    while let Some(start) = rest.find("](") {
        let Some(end) = rest[start..].find(')') else { break };
        rest.replace_range(start + 1..start + end + 1, "");
    }
    let rest = rest.replace(['[', ']'], "");
    for (i, part) in rest.split('`').enumerate() {
        if i % 2 == 1 {
            if part.contains(['{', '}']) || part.contains("*/") {
                out.push_str(&format!("<code>{}</code>", escape(part)));
            } else {
                out.push_str(&format!("{{@code {part}}}"));
            }
        } else {
            out.push_str(&escape(part));
        }
    }
    out
}

fn escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('@', "&#64;").replace("*/", "*&#47;")
}
